for q in data:
    for old, new in reverts:
        if old in q['question']:
            q['question'] = q['question'].replace(old, new)
            count += 1
        if old in q['explanation']:
            q['explanation'] = q['explanation'].replace(old, new)
            count += 1
        q['options'] = [o.replace(old, new) for o in q['options']]

